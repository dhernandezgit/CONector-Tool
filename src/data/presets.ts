export function settingsForPreset(id: string): ConnectorSettings {
  const preset = PRESETS.find((item) => item.id === id);
  if (!preset) return clone(DEFAULT_CONNECTOR);
  const settings = deepMerge(DEFAULT_CONNECTOR, preset.patch);
  settings.name = preset.name;
  return settings;
}

const JOINT_TO_TEMPLATE: Record<string, number> = {
  corner90: 4,
  six: 0,
  horizontal1: 6,
  vertical1: 5,
  vertical2: 5,
  tee: 2,
  flat: 3,
  cross: 1,
};

export function settingsForJoint(presetId: string, color?: string, name?: string): ConnectorSettings {
  const templateId = JOINT_TO_TEMPLATE[presetId];
  if (templateId !== undefined) {
    const base = deepMerge(DEFAULT_CONNECTOR, {
      family: "template",
      template_id: templateId,
      template_scale_xy: 1,
      template_scale_z: 1,
      template_rotate: 0,
      template_mirror: false,
      name: name || PRESETS.find((item) => item.id === `ref${templateId}`)?.name || "Uni?n",
      body_color: color || DEFAULT_CONNECTOR.body_color,
      decor: { ...DEFAULT_CONNECTOR.decor, enabled: false },
    });
    return base;
  }
  const settings = settingsForPreset(presetId);
  settings.name = name || settings.name;
  settings.decor.enabled = false;
  if (color) {
    settings.body_color = color;
    settings.decor.color = color;
  }
  return settings;
}

